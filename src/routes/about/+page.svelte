    <h1 class="text-3xl font-semibold">About the Project</h1>
    <p class="prose">        
        The Land of Israel in Geonic times is a project dedicated to the study of how Jews
        related to their ancestral homeland, as it emerges from the literature of the period,
        from the coming of Islam in the seventh century until the First Crusade in the late eleventh,
        i.e. the so-called geonic period of Jewish history. How did Jews envision the Land and their
        relation to it in this period of Jewish literary and cultural history? This project will map
        a variety of Jewish attitudes toward the Land of Israel in texts composed from the seventh
        century onward; it will identify old and new ways in which the Land continued to matter in
        the Middle Ages. </p>
        <p class="prose">
            To this purpose, we will examine a wide array of early medieval Jewish texts
            of diverse genres, including biblical commentary, poetry, apocalyptic literature, historiography,
            and legal literature. These are texts composed by authors who identified as Jews and who were at
            home both in the Land and abroad. Research has so far tended to focus on the conceptualisation of
            the promised land in the Bible and in the post-biblical Jewish literature of Antiquity and late antiquity.
        </p>
        <p class="prose">The literature of Geonic times remains unexplored in relation to the Land-question.
        However, this period is crucial because it witnesses the beginning of the co-existence of the three
         Abrahamic religions for which the Land is holy. It is also in this period that the Jewish intellectual
          elite made fundamental choices relating to ideas, prayers, and laws developed in the earlier biblical
          and rabbinic timeschoices that would lay the bases for the rest of Jewish history.
    </p>
